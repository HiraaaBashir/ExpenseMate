from dataclasses import dataclass

@dataclass
class Category:
    """Represents a category the transaction belongs to.

    Attributes:
        category_id: Unique identifier, auto-generated by the database.
        category_name: Name of the category.
    """
    category_id: int
    category_name: str

@dataclass
class Transaction:
    """Represents a single income or expense record.

    Attributes:
        transaction_id: Unique identifier, auto-generated by the database.
        amount: The transaction amount in Rs., must be positive.
        type: Either 'income' or 'expense'.
        date: ISO-format date string (e.g., '2026-09-26').
        category_id: Foreign key referencing the associated Category.
    """
    transaction_id: int
    amount: float
    type: str
    date: str
    category_id: int

@dataclass
class Budget:
    """Represents the limit to spend in a month.

    Attributes:
        budget_id: Unique identifier, auto-generated by the database.
        category_id: Foreign key referencing the associated Category.
        month: The month of the budget.
        limit_amount: The amount of budget to limit the budget.
    """
    budget_id: int
    category_id: int
    month: str
    limit_amount: float
